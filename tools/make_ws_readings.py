if __name__ == '__main__':
    d = json.load(open('ws_data.json', encoding='utf8'))
    names = [x['n'] for x in d['weapons'] + d['shields']]
    seal_names = sorted({x['n'] for x in d['seals']})  # 印の名前は辞書の読みの下書きのまま（要確認）
    k = kakasi(); out = {}
    for n in names:
        out[n] = OVERRIDES.get(n) or ''.join(x['hira'] for x in k.convert(n))
    for n in seal_names:
        out.setdefault(n, ''.join(x['hira'] for x in k.convert(n)))
    extra = [n for n in OVERRIDES if n not in out]
    assert not extra, f'OVERRIDES にあるが対象外の名前: {extra}'
    json.dump(out, open('ws_readings.json', 'w', encoding='utf8'), ensure_ascii=False, indent=0)
    print(len(out), '件')
    for n in names:
        if n not in OVERRIDES: print('辞書の読みのまま:', n, out[n])
